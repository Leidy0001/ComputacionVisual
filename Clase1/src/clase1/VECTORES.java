    private void jbtnConsultaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnConsultaActionPerformed
try {
        if (vector == null) {
            throw new misExcepciones("Primero debe crear el vector");
        }

        int posicion = Integer.parseInt(jtxtConsulta.getText());
        int valor = vector.consultar(posicion);

        JOptionPane.showMessageDialog(null, "El valor en la posicion " + posicion + " es: " + valor);

    } catch (misExcepciones ex) {
        JOptionPane.showMessageDialog(null, ex.getMessage());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(null, "Ingrese una posicion numerica valida");
    }        
    }//GEN-LAST:event_jbtnConsultaActionPerformed

    private void jbtnAñadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnAñadirActionPerformed
        try {
            if (vector == null) {
                throw new misExcepciones("Primero debe crear el vector");
            }

            int valor = Integer.parseInt(jtxtValor.getText());
            int posicion = Integer.parseInt(jtxtPosicion.getText());

            vector.agregar(valor, posicion);

            JOptionPane.showMessageDialog(null, "Valor añadido correctamente");

        } catch (misExcepciones ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(null, "Ingrese valores numericos válidos");
    }//GEN-LAST:event_jbtnAñadirActionPerformed
    }
