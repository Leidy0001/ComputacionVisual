    private void jbtnTamañoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnTamañoActionPerformed
                                                                               
 try {
        int tamaño = Integer.parseInt(jtxtTamaño.getText());

        if (tamaño <= 0) {
            throw new misExcepciones("El tamaño debe ser mayor a 0");
        }

        vector = new vector();   
        vector.crearVector(tamaño);
        jbtnTamaño.setEnabled(false);

        JOptionPane.showMessageDialog(null, "Vector creado correctamente");

    } catch (misExcepciones ex) {
        JOptionPane.showMessageDialog(null, ex.getMessage());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(null, "Ingrese un número válido");
    }
   
    }//GEN-LAST:event_jbtnTamañoActionPerformed

    
    
