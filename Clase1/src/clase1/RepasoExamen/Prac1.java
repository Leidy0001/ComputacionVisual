     int[] vector = new int[10];
    int posicion = 0;
 
    public void llenarVector() {
 
        if (posicion >= 10) {
            JOptionPane.showMessageDialog(null,
                    "El vector ya está lleno");
            return;
        }
 
        try {
            int valor = Integer.parseInt(jtxtValor.getText().trim());
 
            if (valor < 1 || valor > 10) {
                JOptionPane.showMessageDialog(null,
                        "Ingrese un número entre 1 y 10");
                return;
            }
 
            for (int i = 0; i < posicion; i++) {
                if (vector[i] == valor) {
                    JOptionPane.showMessageDialog(null,
                            "Ese número ya fue ingresado");
                    return;
                }
            }
 
            vector[posicion] = valor;
            posicion++;
 
            // Agregamos SOLO el nuevo valor al combo (no repoblamos todo)
            actualizandoCombo = true;
            jcbxValores.addItem(valor);
            actualizandoCombo = false;
 
            JOptionPane.showMessageDialog(null,
                    "Número agregado: " + valor);
 
            jtxtValor.setText("");
            jtxtValor.requestFocus();
 
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null,
                    "Ingrese un número entero");
        }
    }
 
    public void clasificar() {
 
        // Ignorar eventos disparados por cambios programáticos del combo
        if (actualizandoCombo) {
            return;
        }
 
        if (jcbxValores.getSelectedIndex() == -1) {
            return;
        }
 
        int valor = (int) jcbxValores.getSelectedItem();
 
        DefaultTableModel modelo
                = (DefaultTableModel) jtblClasificacion.getModel();
 
        // Validación: que no se clasifique el mismo número dos veces en la tabla
        for (int i = 0; i < modelo.getRowCount(); i++) {
            Object par = modelo.getValueAt(i, 0);
            Object impar = modelo.getValueAt(i, 1);
 
            if ((par != null && par.equals(valor))
                    || (impar != null && impar.equals(valor))) {
                JOptionPane.showMessageDialog(null,
                        "Ese número ya fue clasificado en la tabla");
                return;
            }
        }
 
        // Se registra en el historial (orden de selección)
        modeloLista.addElement(String.valueOf(valor));
 
        // Se clasifica en Pares / Impares
        if (valor % 2 == 0) {
            modelo.addRow(new Object[]{valor, null});
        } else {
            modelo.addRow(new Object[]{null, valor});
        }
    }

