    public void Suma() {
        Integer numero1 = Integer.valueOf(jtxtn1.getText());
        Integer numero2 = Integer.valueOf(jtxtn2.getText());
        Integer resultado = numero1 + numero2;
        jtxtResultado.setText(String.valueOf(resultado));
    }

    public void Division() {

        try {
            Integer n1 = Integer.valueOf(jtxtn1.getText());
            Integer n2 = Integer.valueOf(jtxtn2.getText());
            OperacionesBasicas op1 = new OperacionesBasicas(n1, n2);
            jtxtResultado.setText(String.valueOf(op1.Division(n1, n2)));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "division entre 0");

        }
    }

    public void Division1() throws misExcepciones {
        Integer n1 = Integer.valueOf(jtxtn1.getText());
        Integer n2 = Integer.valueOf(jtxtn2.getText());
        OperacionesBasicas op1 = new OperacionesBasicas(n1, n2);
        if ("1".equals(jtxtn2.getText())) {
            throw new misExcepciones("no vale eso");
        } else {
            jtxtResultado.setText(String.valueOf(op1.Division(n1, n2)));
        }
    }
