    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        try {
            Double n1 = Double.valueOf(firstNumberContainer.getText());
            Double n2 = Double.valueOf(secondNumberContainer.getText());
            if(n1 + n2 > 200) throw new MajorThanException("Solo puede ingresar numeros menores a 100 en la presente calculadora");
            String r = String.valueOf(Operations.add(n1, n2));
            resultContainer.setText(r); 
            
        } catch (MajorThanException m){
            JOptionPane.showMessageDialog(null, m.getMessage());
        } catch (NumberFormatException n) {
           JOptionPane.showMessageDialog(null, "Ingrese un numero valido");
        } 
    }//GEN-LAST:event_addButtonActionPerformed

    private void substractButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_substractButtonActionPerformed
        try {
            Double n1 = Double.valueOf(firstNumberContainer.getText());
            Double n2 = Double.valueOf(secondNumberContainer.getText());
            if(n1 + n2 > 200) throw new MajorThanException("Solo puede ingresar numeros menores a 100 en la presente calculadora");
            if(n2 > n1) throw new MinorThanSecondNumberException("El segundo numero es menor al primero ingresado");
            String r = String.valueOf(Operations.substract(n1, n2));
            resultContainer.setText(r); 
            
        } catch (MajorThanException m){
            JOptionPane.showMessageDialog(null, m.getMessage());
        } catch (NumberFormatException n) {
           JOptionPane.showMessageDialog(null, "Ingrese un numero valido");
        } catch (MinorThanSecondNumberException x) {
           JOptionPane.showMessageDialog(null, x.getMessage()); 
        }
    }//GEN-LAST:event_substractButtonActionPerformed

    private void multButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_multButtonActionPerformed
        try {
            Double n1 = Double.valueOf(firstNumberContainer.getText());
            Double n2 = Double.valueOf(secondNumberContainer.getText());
            if(n1 + n2 > 200) throw new MajorThanException("Solo puede ingresar numeros menores a 100 en la presente calculadora");
            String r = String.valueOf(Operations.multiplication(n1, n2));
            if(n1 == 1 || n2 == 1) JOptionPane.showMessageDialog(null, "El resultado es el mismo, se encuentra multiplicando por 1");
            resultContainer.setText(r); 
            
        } catch (MajorThanException m){
            JOptionPane.showMessageDialog(null, m.getMessage());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(null, "Ingrese un numero valido");
        } 
    }//GEN-LAST:event_multButtonActionPerformed

    private void dividedButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dividedButtonActionPerformed
        try {
            Double n1 = Double.valueOf(firstNumberContainer.getText());
            Double n2 = Double.valueOf(secondNumberContainer.getText());
            if(n1 + n2 > 200) throw new MajorThanException("Solo puede ingresar numeros menores a 100 en la presente calculadora");
            if(n2 == 0) throw new ArithmeticException("No se puede dividir para 0");
            String r = String.valueOf(Operations.division(n1, n2));
            if(n2 == 1) JOptionPane.showMessageDialog(null, "El resultado es el mismo, se encuentra dividiendo por 1");
            
            resultContainer.setText(r); 
            
        } catch (MajorThanException m){
            JOptionPane.showMessageDialog(null, m.getMessage());
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(null, "Ingrese un numero valido");
        } catch (ArithmeticException a) {
            JOptionPane.showMessageDialog(null, a.getMessage());
        }
    }//GEN-LAST:event_dividedButtonActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        //prevents to access the values between 10 - 20
        try {
            int placeNumber = Integer.parseInt(place.getText());
            int n = Integer.parseInt(num.getText());
            if(placeNumber <= 20 && n >= 10) throw new BadAccess("Acceso restringido");
            xd[placeNumber] = n;
            JOptionPane.showMessageDialog(null, "Guardado ;D");
        } catch (NumberFormatException n) {
            JOptionPane.showMessageDialog(null, "Ingrese un numero valido");
        } catch (BadAccess a) {
            JOptionPane.showMessageDialog(null, a.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

