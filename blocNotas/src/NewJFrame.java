    private void jmnuTipoLetraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jmnuTipoLetraActionPerformed
        JTextArea area = getTextAreaActual();
if (area == null) return;

String[] fuentes = java.awt.GraphicsEnvironment.getLocalGraphicsEnvironment().getAvailableFontFamilyNames();
String seleccion = (String) JOptionPane.showInputDialog(this, "Elige tipo de letra:",
        "Tipo de Letra", JOptionPane.PLAIN_MESSAGE, null, fuentes, area.getFont().getFamily());

if (seleccion != null) {
    Font actual = area.getFont();
    area.setFont(new Font(seleccion, actual.getStyle(), actual.getSize()));
}
    }//GEN-LAST:event_jmnuTipoLetraActionPerformed

    private void jmnuColorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jmnuColorActionPerformed
        JTextArea area = getTextAreaActual();
if (area == null) return;

Color nuevoColor = JColorChooser.showDialog(this, "Elige un color", area.getForeground());
if (nuevoColor != null) {
    area.setForeground(nuevoColor);
}
    }//GEN-LAST:event_jmnuColorActionPerformed

    private void jmnuTamañoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jmnuTamañoActionPerformed
        JTextArea area = getTextAreaActual();
if (area == null) return;

String input = JOptionPane.showInputDialog(this, "Tamaño de letra:", area.getFont().getSize());
if (input != null) {
    try {
        int tamaño = Integer.parseInt(input.trim());
        Font actual = area.getFont();
        area.setFont(new Font(actual.getFamily(), actual.getStyle(), tamaño));
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Ingresa un número válido.");
    }
}
    }//GEN-LAST:event_jmnuTamañoActionPerformed

