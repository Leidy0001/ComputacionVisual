    private void jmnuGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jmnuGuardarActionPerformed
        JTextArea area = getTextAreaActual();
if (area == null) return;

JFileChooser chooser = new JFileChooser();
chooser.setDialogTitle("Guardar archivo");
if (chooser.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
    File archivo = chooser.getSelectedFile();
    if (!archivo.getName().toLowerCase().endsWith(".txt")) {
        archivo = new File(archivo.getAbsolutePath() + ".txt");
    }
    try (BufferedWriter bw = new BufferedWriter(new FileWriter(archivo))) {
        bw.write(area.getText());
        jTabbedPane1.setTitleAt(jTabbedPane1.getSelectedIndex(), archivo.getName());
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    }
    // en vez de: jTabbedPane1.setTitleAt(jTabbedPane1.getSelectedIndex(), archivo.getName());
int idx = jTabbedPane1.getSelectedIndex();
jTabbedPane1.setTitleAt(idx, archivo.getName());
agregarBotonCerrar((JPanel) jTabbedPane1.getSelectedComponent(), archivo.getName());
}

    }//GEN-LAST:event_jmnuGuardarActionPerformed

