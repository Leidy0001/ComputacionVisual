    private JTextArea getTextAreaActual() {
    JPanel panel = (JPanel) jTabbedPane1.getSelectedComponent();
    if (panel == null) return null;
    JScrollPane scroll = (JScrollPane) panel.getComponent(0);
    return (JTextArea) scroll.getViewport().getView();
    }
    private void agregarBotonCerrar(JPanel panelContenido, String titulo) {
    JPanel panelPestaña = new JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.LEFT, 0, 0));
    panelPestaña.setOpaque(false);

    javax.swing.JLabel etiqueta = new javax.swing.JLabel(titulo);
    etiqueta.setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 0, 0, 5));

    javax.swing.JButton botonCerrar = new javax.swing.JButton("×");
    botonCerrar.setPreferredSize(new java.awt.Dimension(18, 18));
    botonCerrar.setMargin(new java.awt.Insets(0, 0, 0, 0));
    botonCerrar.setFocusable(false);
    botonCerrar.setBorderPainted(false);
    botonCerrar.setContentAreaFilled(false);
    botonCerrar.setFont(botonCerrar.getFont().deriveFont(java.awt.Font.BOLD));

    botonCerrar.addActionListener(evt -> {
        int index = jTabbedPane1.indexOfComponent(panelContenido);
        if (index != -1) {
            if (jTabbedPane1.getTabCount() == 1) {
                JOptionPane.showMessageDialog(this, "No puedes cerrar la última pestaña.");
                return;
            }
            int confirmar = JOptionPane.showConfirmDialog(this,
                    "¿Cerrar \"" + jTabbedPane1.getTitleAt(index) + "\"? Los cambios no guardados se perderán.",
                    "Cerrar pestaña", JOptionPane.YES_NO_OPTION);
            if (confirmar == JOptionPane.YES_OPTION) {
                jTabbedPane1.remove(index);
            }
        }
    });

    panelPestaña.add(etiqueta);
    panelPestaña.add(botonCerrar);

    int index = jTabbedPane1.indexOfComponent(panelContenido);
    jTabbedPane1.setTabComponentAt(index, panelPestaña);
}
    
